#!/usr/bin/env python3
"""Build the POFlow translation bundle (v2.1).

Source of truth (edit these, then run `python3 tools/build_i18n.py`):
  tools/i18n/ar-en.json   AR → EN dictionary (exact UI strings and reusable phrases)
  tools/i18n/patterns.js  regex patterns for strings with numbers (e.g. "3 قاعة")
  tools/i18n/engine.js    runtime engine (text nodes + attributes, dark mode, toggles)
Outputs:
  apps-script/I18n.html   included by doGet in Index / Denied / HowTo
  assets/i18n.js          the same bundle for the GitHub Pages login page
`--check` fails if the outputs are stale (used by CI)."""
import json, sys, pathlib
R = pathlib.Path(__file__).resolve().parent.parent
d = json.loads((R / 'tools/i18n/ar-en.json').read_text(encoding='utf-8'))
d = {k: v for k, v in d.items() if not k.startswith('//')}
js = ('/* POFlow i18n bundle — generated by tools/build_i18n.py; do not edit by hand */\n'
      'window.I18N_DICT=' + json.dumps(d, ensure_ascii=False, separators=(',', ':')) + ';\n'
      + (R / 'tools/i18n/patterns.js').read_text(encoding='utf-8') + '\n'
      + (R / 'tools/i18n/engine.js').read_text(encoding='utf-8'))
html = '<script>\n' + js.replace('</script', '<\\/script') + '\n</script>\n'
outs = {R / 'apps-script/I18n.html': html, R / 'assets/i18n.js': js}
if '--check' in sys.argv:
    stale = [str(p.relative_to(R)) for p, c in outs.items() if not p.exists() or p.read_text(encoding='utf-8') != c]
    if stale: sys.exit('✖ stale i18n bundle: ' + ', '.join(stale) + ' — run python3 tools/build_i18n.py')
    print(f'✔ i18n bundle up to date ({len(d)} strings)'); sys.exit(0)
for p, c in outs.items(): p.write_text(c, encoding='utf-8')
print(f'✔ built I18n.html + assets/i18n.js ({len(d)} strings)')
